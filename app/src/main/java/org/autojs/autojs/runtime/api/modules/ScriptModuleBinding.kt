package org.autojs.autojs.runtime.api.modules

import org.autojs.autojs.runtime.ScriptRuntime
import org.mozilla.javascript.Context
import org.mozilla.javascript.Scriptable
import org.mozilla.javascript.VarScope

/**
 * What the KSP processor generates for every @ScriptModule class (`org.autojs.autojs.runtime.api.modules.generated`):
 * the mount table ([spec]) and the dispatch of calls, getters and setters by member id. No reflection is involved; the
 * generated code calls the module's Kotlin functions directly (roadmap D5).
 *
 * zh-CN: KSP 处理器为每个 @ScriptModule 类生成的绑定: 挂载表 ([spec]) 与按成员编号分发的调用, getter 与 setter. 不使用反射, 生成代码直接调用
 * 模块的 Kotlin 函数 (D5).
 */
interface ScriptModuleBinding<M : Any> {

    val spec: ScriptModuleSpec

    /** The module instance: the object itself, or a new instance for the given runtime. */
    fun create(runtime: ScriptRuntime?): M

    /** Calls function [id] of [spec], or the module itself ([INVOKE]) or its constructor ([CONSTRUCT]). */
    fun call(module: M, id: Int, cx: Context, scope: VarScope, thisObj: Any?, args: Array<out Any?>): Any?

    /** Reads accessor [id] of [spec] (getters on every read, properties once at mount). */
    fun get(module: M, id: Int, scope: VarScope): Any?

    /** Writes accessor [id] of [spec] if it is writable. */
    fun set(module: M, id: Int, value: Any?)

    /**
     * The prototype of the module object (a `List` is a chain, nearest first; a [ScriptNameLookup] resolves names), or
     * null to keep the default one. For an assign module it is the prototype of the global object.
     */
    fun prototype(module: M): Any?

    /** Runs the module's `@ScriptInstall` function ([ScriptModuleSpec.hasInstall]). */
    fun install(module: M, installation: ScriptModuleInstallation) {}

    /** Reads [name] of a proxy module through its `@ScriptProxyGet` function ([ScriptModuleSpec.hasProxyGet]). */
    fun proxyGet(module: M, members: Scriptable, name: String): Any? = Scriptable.NOT_FOUND

    /** Writes [name] of a proxy module through its `@ScriptProxySet` function ([ScriptModuleSpec.hasProxySet]). */
    fun proxySet(module: M, members: Scriptable, name: String, value: Any?) {}

    companion object {
        const val INVOKE = -1
        const val CONSTRUCT = -2
    }

}

/**
 * The bindings of one compilation unit, generated by the processor as `generated.ScriptModules` for the host and as
 * `generated.TestScriptModules` for the unit test fixtures (KSP option `scriptModules.registry`). The mounter finds
 * modules and their sub-modules here, so nothing is scanned or reflected at run time.
 *
 * zh-CN: 一个编译单元的全部绑定, 由处理器生成 (宿主为 `generated.ScriptModules`, 单元测试夹具为 `generated.TestScriptModules`). 挂载器在这里查找模块
 * 与子模块, 运行时不扫描也不反射.
 */
interface ScriptModuleRegistry {

    /** Top-level modules sorted by name, then the sub-modules sorted by parent and name. */
    val bindings: List<ScriptModuleBinding<*>>

    /** The top-level module bound to [name] (its name, an alias or a `$` form; an assign module by its name), or null. */
    fun find(name: String): ScriptModuleBinding<*>? = bindings.firstOrNull { it.spec.parent == null && (it.spec.name == name || name in it.spec.names) }

    /** The sub-modules of the module declared by class [className]. */
    fun childrenOf(className: String): List<ScriptModuleBinding<*>> = bindings.filter { it.spec.parent == className }

    /** Names of the top-level modules, as listed by the per-module debug printing switches (appendix C Q4). */
    val moduleNames: List<String>
        get() = bindings.filter { it.spec.parent == null }.map { it.spec.name }

}

/**
 * The mount table of a module. It only holds plain values (no annotation types), so the annotations module stays a
 * compile-time dependency.
 */
class ScriptModuleSpec(
    val name: String,
    /** Qualified name of the @ScriptModule class. */
    val className: String,
    val aliases: List<String>,
    val dollarPrefix: Boolean,
    val eager: Boolean,
    /** Qualified class name of the parent module, or null for a module on the global object. */
    val parent: String?,
    /** Rhino attributes of the names binding the module object on its target. */
    val attributes: Int,
    /** Whether an event emitter object ends the prototype chain of the module object. */
    val emitter: Boolean,
    /** The JavaScript built-in object (as `Math`) the module extends ([ScriptBuiltInExtender]), or null. */
    val builtIn: String?,
    /** JS `length` of the callable module object, or -1 when the module object is not callable. */
    val invokeLength: Int,
    /** JS `length` of the constructor, or -1 when the module object is not a constructor. */
    val constructLength: Int,
    val functions: List<ScriptFunctionSpec>,
    val accessors: List<ScriptAccessorSpec>,
    val javaClasses: List<ScriptJavaClassSpec>,
    /** No module object: every member goes on the global object, the prototypes on the global object (`global`, `legacy`). */
    val assign: Boolean = false,
    /** The module object is a proxy without own properties that reads from the members object ([ScriptProxyObject]). */
    val proxy: Boolean = false,
    /** The module has a `@ScriptInstall` function. */
    val hasInstall: Boolean = false,
    /** The proxy module has a `@ScriptProxyGet` / `@ScriptProxySet` function. */
    val hasProxyGet: Boolean = false,
    val hasProxySet: Boolean = false,
) {
    /**
     * Every name the module object is bound to: the name and the aliases, each with its `$` form if [dollarPrefix]; none
     * for an assign module.
     */
    val names: List<String> = if (assign) emptyList() else (listOf(name) + aliases).flatMap { if (dollarPrefix) listOf(it, "\$$it") else listOf(it) }
}

class ScriptFunctionSpec(
    val id: Int,
    val name: String,
    val aliases: List<String>,
    val onModule: Boolean,
    val onGlobal: Boolean,
    val attributes: Int,
    val length: Int,
    /** A `toString` that converts its arguments: the module object also gets the hidden custom toString marker. */
    val functionalToString: Boolean,
    /** Bound on the module's built-in object when it is extended (as `Math.sum`). */
    val onBuiltIn: Boolean = false,
    /** Bound on the built-in object's prototype, taking the receiver as its first argument (as `[].distinct()`). */
    val onBuiltInPrototype: Boolean = false,
    /** Bound on the global object when the built-in object is extended (as `parseFloat`). */
    val onBuiltInGlobal: Boolean = false,
)

class ScriptAccessorSpec(
    val id: Int,
    val name: String,
    /** True for an accessor property read on every access, false for a data property read once at mount. */
    val getter: Boolean,
    val writable: Boolean,
    val onModule: Boolean,
    val onGlobal: Boolean,
    val attributes: Int,
    /** Bound on the module's built-in object when it is extended (as `Number.ICU`); data properties only. */
    val onBuiltIn: Boolean = false,
    /** Bound on the global object when the built-in object is extended; data properties only. */
    val onBuiltInGlobal: Boolean = false,
)

class ScriptJavaClassSpec(
    val name: String,
    val type: Class<*>,
    val onModule: Boolean,
    val onGlobal: Boolean,
    val attributes: Int,
)
