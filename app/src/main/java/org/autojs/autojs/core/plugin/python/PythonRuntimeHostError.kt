package org.autojs.autojs.core.plugin.python

/** Stable host-side failures for the independent Python Runtime plugin. */
internal enum class PythonRuntimeHostError(val stableCode: String) {
    /** Legacy stable code retained for the unsupported packaged-INRT host flavor. */
    PREVIEW_DISABLED("PYTHON_RUNTIME_PREVIEW_DISABLED"),
    SOURCE_INVALID("PYTHON_RUNTIME_SOURCE_INVALID"),
    WORKSPACE_INVALID("PYTHON_RUNTIME_WORKSPACE_INVALID"),
    ENTRY_MODE_INVALID("PYTHON_RUNTIME_ENTRY_MODE_INVALID"),
    STDIN_INVALID("PYTHON_RUNTIME_STDIN_INVALID"),
    INTERACTIVE_INPUT_NOT_ALLOWED("PYTHON_RUNTIME_INTERACTIVE_INPUT_NOT_ALLOWED"),
    INTERACTIVE_INPUT_FAILED("PYTHON_RUNTIME_INTERACTIVE_INPUT_FAILED"),
    HOST_CAPABILITY_SNAPSHOT_INVALID("PYTHON_RUNTIME_HOST_CAPABILITY_SNAPSHOT_INVALID"),
    PLUGIN_MISSING("PYTHON_RUNTIME_PLUGIN_MISSING"),
    PLUGIN_DISABLED("PYTHON_RUNTIME_PLUGIN_DISABLED"),
    PROVIDER_UNTRUSTED("PYTHON_RUNTIME_PROVIDER_UNTRUSTED"),
    PROVIDER_INCOMPATIBLE("PYTHON_RUNTIME_PROVIDER_INCOMPATIBLE"),
    PROVIDER_IDENTITY_CHANGED("PYTHON_RUNTIME_PROVIDER_IDENTITY_CHANGED"),
    BIND_FAILED("PYTHON_RUNTIME_BIND_FAILED"),
    BIND_TIMEOUT("PYTHON_RUNTIME_BIND_TIMEOUT"),
    BUSY("PYTHON_RUNTIME_BUSY"),
    SESSION_REJECTED("PYTHON_RUNTIME_SESSION_REJECTED"),
    EXECUTION_TIMEOUT("PYTHON_RUNTIME_EXECUTION_TIMEOUT"),
    EXECUTION_FAILED("PYTHON_RUNTIME_EXECUTION_FAILED"),
    EXECUTION_LOST("PYTHON_RUNTIME_EXECUTION_LOST"),
    CONTRACT_VIOLATION("PYTHON_RUNTIME_CONTRACT_VIOLATION"),
}

internal class PythonRuntimeHostException(
    val error: PythonRuntimeHostError,
    detail: String,
    cause: Throwable? = null,
) : IllegalStateException("${error.stableCode}: $detail", cause)
