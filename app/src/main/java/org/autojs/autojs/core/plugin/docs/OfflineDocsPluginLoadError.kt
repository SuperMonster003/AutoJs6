package org.autojs.autojs.core.plugin.docs

enum class OfflineDocsPluginLoadError {
    PLUGIN_NOT_FOUND,
    PACKAGE_NAME_UNSUPPORTED,
    DISCOVERY_FAILED,
    PLUGIN_DISABLED,
    IN_PROCESS_TRUST_REQUIRED,
    CONTRACT_METADATA_INVALID,
    CONTRACT_VERSION_UNSUPPORTED,
    CONTENT_VERSION_INVALID,
    CONTENT_FORMAT_UNSUPPORTED,
    ASSET_ROOT_UNSUPPORTED,
    ENTRY_POINT_UNSUPPORTED,
    FILE_COUNT_INVALID,
    TOTAL_BYTES_INVALID,
    CONTENT_SHA256_INVALID,
    HOST_VERSION_TOO_LOW,
    HOST_VERSION_TOO_HIGH,
    PACKAGE_CONTEXT_FAILED,
    INVENTORY_MISSING,
    INVENTORY_INVALID,
    CONTENT_FILE_COUNT_MISMATCH,
    CONTENT_TOTAL_BYTES_MISMATCH,
    CONTENT_SHA256_MISMATCH,
    CONTENT_FILE_MISSING,
    CONTENT_FILE_SIZE_MISMATCH,
    CONTENT_FILE_HASH_MISMATCH,
    ENTRY_POINT_MISSING,
    PLUGIN_CHANGED_DURING_LOAD,
}

class OfflineDocsPluginLoadException(
    val code: OfflineDocsPluginLoadError,
    val packageName: String? = null,
    message: String,
    cause: Throwable? = null,
) : IllegalStateException(message, cause)
