/* Generate the Rhino-compatible text API directly from the pinned upstream source. */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const terser = require('terser');
const adaptRhino = require('./rhino-compat.cjs');

// The Bundled Libraries plugin carries the module (P5.2) and tests it (appendix C Q182): its assets/modules comes from
// --out <dir> or AUTOJS6_BUNDLED_LIBRARIES_MODULES, by default a checkout next to this repository.
function outputDirectory() {
    const index = process.argv.indexOf('--out');
    const given = index >= 0 ? process.argv[index + 1] : process.env.AUTOJS6_BUNDLED_LIBRARIES_MODULES;
    const directory = path.resolve(given || path.join(__dirname, '../../../AutoJs6-Plugin-Bundled-Libraries/app/src/main/assets/modules'));
    if (!fs.statSync(directory, { throwIfNoEntry: false })?.isDirectory()) {
        throw new Error(`${directory} is not a directory. Pass --out <app/src/main/assets/modules of AutoJs6-Plugin-Bundled-Libraries>.`);
    }
    return directory;
}

async function build() {
    const packageRoot = path.dirname(require.resolve('pangu/package.json'));
    const upstream = require('pangu/package.json');
    const source = fs.readFileSync(path.join(packageRoot, 'src/shared/index.ts'), 'utf8');
    const compiled = ts.transpileModule(adaptRhino(source), {
        fileName: 'pangu.ts',
        reportDiagnostics: true,
        compilerOptions: {
            target: ts.ScriptTarget.ES5,
            module: ts.ModuleKind.CommonJS,
            downlevelIteration: true,
            ignoreDeprecations: '6.0',
            removeComments: true,
        },
    });
    if (compiled.diagnostics.length) {
        throw new Error(ts.formatDiagnosticsWithColorAndContext(compiled.diagnostics, {
            getCurrentDirectory: () => __dirname,
            getCanonicalFileName: name => name,
            getNewLine: () => '\n',
        }));
    }
    const minified = await terser.minify(compiled.outputText + '\nmodule.exports = exports.pangu;\n', {
        ecma: 5,
        compress: true,
        mangle: true,
        format: { ascii_only: true, comments: false },
    });
    const assets = outputDirectory();
    const banner = `/*! pangu.js ${upstream.version} | Copyright (c) 2013 Vinta | MIT
 * https://github.com/vinta/pangu.js | Text API, transpiled for AutoJs6 Rhino.
 * Generated by tools/pangu/build.cjs. License: pangu.LICENSE.txt.
 */\n`;
    const outputs = {
        'pangu.min.js': banner + minified.code + '\n',
        'pangu.LICENSE.txt': fs.readFileSync(path.join(packageRoot, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n'),
    };
    for (const [name, content] of Object.entries(outputs)) {
        const output = path.join(assets, name);
        if (process.argv.includes('--check')) {
            if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== content) {
                throw new Error(`${name} differs from the pinned upstream build. Run npm run build.`);
            }
        } else {
            fs.writeFileSync(output, content);
        }
        console.log(`${name}: ${Buffer.byteLength(content)} bytes`);
    }
}

build().catch(error => {
    console.error(error);
    process.exitCode = 1;
});
