import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..'),workspace=resolve(root,'..');
const node=resolve(workspace,'AutoJs6-Plugin-NodeJs-Runtime'),bun=resolve(workspace,'AutoJs6-Plugin-Bun-Runtime');
const native=readFileSync(resolve(root,'app/src/main/java/org/autojs/autojs/engine/RuntimeJavaInterop.kt'),'utf8');
const routes=[...native.match(/val methods\s*=\s*setOf\(([^)]*)\)/)[1].matchAll(/"([^"]+)"/g)].map(x=>x[1]).sort();
const {HOST_API_METHODS}=await import(pathToFileURL(resolve(bun,'app/src/main/assets/autojs6/host-client.mjs')).href);
assert.deepEqual([...HOST_API_METHODS['java.interop']].sort(),routes);
const source=readFileSync(resolve(node,'app/src/main/cpp/node_bridge_sources.cpp'),'utf8');
const body=source.slice(source.indexOf('  // Shared Java object facade'),source.indexOf('  // Main Java facade transport.'));
const api=new Function(body+';return __autojs6_create_java(()=>{});')();
const types=readFileSync(resolve(node,'docs/nodejs/types/autojs6-node/java.d.ts'),'utf8');
const declaration=types.slice(types.indexOf('    interface API {'));
for(const method of Object.keys(api))assert(new RegExp('\\b'+method+'(?:"|\\s|[<(?:])').test(declaration),'Missing declaration: '+method);
assert(source.includes('__autojs6_create_java.toString()'));
assert(source.includes('modules.set("java",createJava('));
execFileSync(process.execPath,[resolve(bun,'tools/host-client/sync-java-interop.mjs'),'--check'],{stdio:'inherit'});
console.log(`Java interop coverage: ${routes.length} native routes, ${Object.keys(api).length} shared facade members, Node/Bun/Worker declarations synchronized`);
