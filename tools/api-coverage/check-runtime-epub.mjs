import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..'), workspace = resolve(root, '..');
const node = resolve(workspace, 'AutoJs6-Plugin-NodeJs-Runtime'), bun = resolve(workspace, 'AutoJs6-Plugin-Bun-Runtime');
const read = path => readFileSync(path, 'utf8');
execFileSync(process.execPath, [resolve(bun, 'tools/host-client/sync-epub.mjs'), '--check'], {stdio: 'inherit'});
const source = read(resolve(node, 'app/src/main/cpp/node_bridge_sources.cpp'));
const start = source.indexOf('  // Shared EPUB facade.'), end = source.indexOf('  // End shared EPUB facade.', start);
assert(start >= 0 && end > start);
const factory = new Function(source.slice(start, end) + ';return __autojs6_create_epub;')();
const epub = factory(() => { throw Error('Export inspection must not call the host'); });
const types = read(resolve(node, 'docs/nodejs/types/autojs6-node/epub.d.ts'));
const docs = read(resolve(workspace, 'AutoJs6-Documentation/api/runtimeApis.md')).split('## Node.js / Bun / Worker 的 EPUB')[1];
assert(docs, 'EPUB runtime reference missing');
const rhino = read(resolve(root, 'app/src/main/java/org/autojs/autojs/runtime/api/augment/epub/Epub.kt'));
const registrations = rhino.split('override val selfAssignmentFunctions = listOf(')[1].split('\n    )')[0];
let count = 0;
for (const [, method] of registrations.matchAll(/::(\w+)\.name/g)) {
  assert.equal(typeof epub[method], 'function', 'Missing EPUB method ' + method);
  assert(types.includes(method + '('), 'Missing EPUB declaration ' + method);
  assert(docs.includes(method), 'Missing EPUB documentation ' + method);
  count++;
}
assert.equal(count, 20);
assert(epub.EpubError('test', 'NOT_EPUB') instanceof epub.EpubError);
assert(source.includes('for(const id of epubClients)closeEpub(id)'));
const host = read(resolve(root, 'app/src/main/java/org/autojs/autojs/engine/RuntimeEpubBridge.kt'));
for (const method of ['getCapabilities', 'openBook', 'openReader']) assert(host.includes('EpubPluginHost.' + method));
assert(host.includes('EpubBookOperations') && host.includes('scope.cancel()'));
const contract = read(resolve(root, 'plugin-api/epub-api/src/main/java/org/autojs/plugin/epub/api/EpubActions.kt'));
const literal = name => contract.match(new RegExp('const val ' + name + ' = "([^"]+)"'))?.[1];
const plugin = resolve(workspace, 'AutoJs6-Plugin-Three-Folio-EPUB');
const manifest = read(resolve(plugin, 'app/src/main/AndroidManifest.xml'));
const service = name => manifest.match(new RegExp('<service\\s+android:name="\\.service\\.' + name + '"[\\s\\S]*?</service>'))?.[0];
assert(service('ThreeFolioEpubPluginService')?.includes('android:permission="' + literal('PLUGIN_PERMISSION') + '"'));
assert(service('ThreeFolioEpubPackagedService')?.includes('android:permission="' + literal('PACKAGED_PERMISSION') + '"'));
assert(service('ThreeFolioEpubPackagedService').includes('android:name="' + literal('PACKAGED_SERVICE_ACTION') + '"'));
const reader = manifest.match(/<activity-alias\s+android:name="\.PackagedEpubReaderActivity"[\s\S]*?<\/activity-alias>/)?.[0];
assert(reader?.includes('android:permission="' + literal('PACKAGED_PERMISSION') + '"'));
assert(reader.includes('android:name="' + literal('PACKAGED_READER_ACTIVITY_ACTION') + '"'));
const guard = read(resolve(plugin, 'app/src/main/java/io/github/supermonster003/autojs6/plugin/three/folio/epub/service/CallerGuard.kt'));
assert(guard.includes('ownerUid != null && uid != ownerUid'));
const preparer = read(resolve(root, 'app/src/main/java/org/autojs/autojs/apkbuilder/template/RemoteApkBuildRequestPreparer.kt'));
assert.equal(preparer.split('EpubActions.PACKAGED_PERMISSION').length - 1, 2);
console.log(JSON.stringify({rhinoEpubMethods: count, nodeBunWorker: true, sharedPlugin: true, packagedServiceAndReader: true}));
