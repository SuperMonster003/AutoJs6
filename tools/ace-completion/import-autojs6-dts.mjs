#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import {
  BUNDLED_AUTOJS6_DTS_ROOT,
  PROJECT_ROOT,
  normalizeLineEndings,
  relativeToRoot,
  writeIfChanged,
} from "./indices-utils.mjs";

const DEFAULT_SOURCE_ROOT = path.resolve(PROJECT_ROOT, "../AutoJs6-TypeScript-Declarations");
const sourceRoot = path.resolve(process.argv[2] || process.env.AUTOJS6_DTS_ROOT || DEFAULT_SOURCE_ROOT);
const sourceAutoJs6Root = path.join(sourceRoot, "declarations", "autojs6");

if (!fs.existsSync(sourceAutoJs6Root)) {
  throw new Error(`AutoJs6 declaration source not found: ${sourceAutoJs6Root}`);
}

fs.mkdirSync(BUNDLED_AUTOJS6_DTS_ROOT, { recursive: true });

const dtsFiles = fs.readdirSync(sourceAutoJs6Root)
  .filter((fileName) => fileName === "aj6-declarations.d.ts" ||
    fileName === "aj6-jsx-element-extension.d.ts" ||
    /^aj6-int-.+\.d\.ts$/.test(fileName) || /^aj6-jsox-(?:(?:array|number|math)-)?extensions\.d\.ts$/.test(fileName))
  .sort((a, b) => a.localeCompare(b));

if (dtsFiles.length === 0) {
  throw new Error(`No selected AutoJs6 declaration files found under ${sourceAutoJs6Root}`);
}

for (const staleFile of fs.readdirSync(BUNDLED_AUTOJS6_DTS_ROOT)) {
  if (
    staleFile === "index.d.ts" ||
    staleFile === "BUNDLED_DECLARATIONS.md" ||
    staleFile === "LICENSE" ||
    staleFile === "package.json" ||
    staleFile === "aj6-declarations.d.ts" ||
    /^aj6-int-.+\.d\.ts$/.test(staleFile) ||
    /^aj6-jsox-(?:(?:array|number|math)-)?extensions\.d\.ts$/.test(staleFile)
  ) {
    fs.rmSync(path.join(BUNDLED_AUTOJS6_DTS_ROOT, staleFile), { force: true });
  }
}

for (const fileName of dtsFiles) {
  const sourcePath = path.join(sourceAutoJs6Root, fileName);
  const destinationPath = path.join(BUNDLED_AUTOJS6_DTS_ROOT, fileName);
  const content = normalizeLineEndings(fs.readFileSync(sourcePath, "utf8")).replace(/^\uFEFF/, "")
    .replaceAll('/// <reference path="../index.d.ts" />', '/// <reference path="./index.d.ts" />');
  writeIfChanged(destinationPath, content);
}

for (const fileName of ["LICENSE", "package.json"]) {
  const sourcePath = path.join(sourceRoot, fileName);
  if (fs.existsSync(sourcePath)) {
    writeIfChanged(path.join(BUNDLED_AUTOJS6_DTS_ROOT, fileName), normalizeLineEndings(fs.readFileSync(sourcePath, "utf8")));
  }
}

const references = dtsFiles
  .filter(fileName => !fileName.startsWith("aj6-jsox-"))
  .map((fileName) => `/// <reference path="./${fileName}" />`)
  .join("\n");
writeIfChanged(
  path.join(BUNDLED_AUTOJS6_DTS_ROOT, "index.d.ts"),
  [
    "// Generated by tools/ace-completion/import-autojs6-dts.mjs.",
    "// Native optional groups and opt-in JSOX extensions are loaded separately by the editor.",
    references,
    "",
  ].join("\n"),
);

const packageJsonPath = path.join(sourceRoot, "package.json");
const packageInfo = fs.existsSync(packageJsonPath)
  ? JSON.parse(fs.readFileSync(packageJsonPath, "utf8"))
  : {};
writeIfChanged(
  path.join(BUNDLED_AUTOJS6_DTS_ROOT, "BUNDLED_DECLARATIONS.md"),
  [
    "# Bundled AutoJs6 TypeScript Declarations",
    "",
    `- Source package: ${packageInfo.name || "AutoJs6-TypeScript-Declarations"}`,
    `- Version: ${packageInfo.version || "unknown"}`,
    `- License: ${packageInfo.license || "MPL-2.0"}`,
    "- Source location: local AutoJs6-TypeScript-Declarations checkout at import time.",
    "- Core files: `aj6-declarations.d.ts`, `aj6-int-*.d.ts` and `aj6-jsx-element-extension.d.ts`.",
    "- Conditional files: `aj6-jsox-*-extensions.d.ts` and their aggregate entry. These are copied without default index references.",
    "- Native optional groups (`aj6-main-app.d.ts`, Android, libraries and resources) are synchronized by the declaration publisher.",
    "- Current use: generation input for ACE static completion indices.",
    "",
  ].join("\n"),
);

console.log(`Imported ${dtsFiles.length} AutoJs6 declaration files into ${relativeToRoot(BUNDLED_AUTOJS6_DTS_ROOT)}.`);
