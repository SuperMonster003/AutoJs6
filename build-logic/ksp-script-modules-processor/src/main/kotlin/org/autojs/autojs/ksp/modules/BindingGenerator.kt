package org.autojs.autojs.ksp.modules

/**
 * Writes the Kotlin source of `<Module>Binding` (roadmap T2 / T4): the mount table as a `ScriptModuleSpec`, a `when (id)`
 * dispatch with one private function per script function, and argument conversion derived from the real Kotlin
 * signatures. Every conversion, error and result normalization goes through `ScriptArgs`, so the conversion table lives
 * in one place of the runtime.
 *
 * zh-CN: 生成 `<模块>Binding` 的 Kotlin 源码 (T2 / T4): 以 ScriptModuleSpec 表示的挂载表, `when (id)` 分发 (每个脚本函数一个私有函数),
 * 以及按真实 Kotlin 签名推导的参数转换. 转换, 错误与返回值归一化都经由 ScriptArgs, 转换表在运行时只有一处实现.
 */
internal object BindingGenerator {

    const val PACKAGE = "org.autojs.autojs.runtime.api.modules.generated"
    private const val RUNTIME_PACKAGE = "org.autojs.autojs.runtime.api.modules"

    fun generate(model: ModuleModel): String = buildString {
        val m = model.qualifiedName
        appendLine("// Generated by ksp-script-modules-processor from $m. DO NOT EDIT.")
        appendLine("@file:Suppress(\"unused\", \"RedundantVisibilityModifier\", \"RemoveRedundantQualifierName\", \"UNCHECKED_CAST\", \"USELESS_CAST\", \"UNUSED_PARAMETER\", \"KotlinConstantConditions\", \"PLATFORM_CLASS_MAPPED_TO_KOTLIN\", \"REDUNDANT_SPREAD_OPERATOR_IN_NAMED_FORM_IN_FUNCTION\")")
        appendLine()
        appendLine("package $PACKAGE")
        appendLine()
        appendLine("import org.autojs.autojs.runtime.ScriptRuntime")
        appendLine("import $RUNTIME_PACKAGE.ScriptAccessorSpec")
        appendLine("import $RUNTIME_PACKAGE.ScriptArgs")
        appendLine("import $RUNTIME_PACKAGE.ScriptFunctionSpec")
        appendLine("import $RUNTIME_PACKAGE.ScriptJavaClassSpec")
        appendLine("import $RUNTIME_PACKAGE.ScriptModuleBinding")
        appendLine("import $RUNTIME_PACKAGE.ScriptModuleSpec")
        appendLine("import org.mozilla.javascript.Context")
        appendLine("import org.mozilla.javascript.VarScope")
        appendLine()
        appendLine("/** Binding of script module ${lit(model.name)} declared by [$m] (${model.source}). */")
        appendLine("public object ${model.bindingName} : ScriptModuleBinding<$m> {")
        appendLine()
        appendSpec(model)
        appendLine()
        appendCreate(model)
        appendLine()
        appendCall(model)
        appendLine()
        appendGet(model)
        appendLine()
        appendSet(model)
        appendLine()
        appendLine("    override fun prototype(module: $m): Any? = ${model.prototype?.let { "module.${id(it.kotlinName)}${if (it.isFunction) "()" else ""}" } ?: "null"}")
        model.functions.forEach { group ->
            appendLine()
            appendDispatcher("f${group.id}", "${model.name}.${group.name}", group.overloads, model)
        }
        model.invoke?.let {
            appendLine()
            appendDispatcher("invoke", "${model.name}()", listOf(it), model)
        }
        model.construct?.let {
            appendLine()
            appendDispatcher("construct", "new ${model.name}()", listOf(it), model, constructor = true)
        }
        appendLine()
        appendLine("}")
    }

    private fun StringBuilder.appendSpec(model: ModuleModel) {
        appendLine("    override val spec: ScriptModuleSpec = ScriptModuleSpec(")
        appendLine("        name = ${lit(model.name)},")
        appendLine("        aliases = ${list(model.aliases.map(::lit))},")
        appendLine("        dollarPrefix = ${model.dollarPrefix},")
        appendLine("        eager = ${model.eager},")
        appendLine("        parent = ${model.parent?.let(::lit) ?: "null"},")
        appendLine("        invokeLength = ${model.invoke?.required ?: -1},")
        appendLine("        constructLength = ${model.construct?.required ?: -1},")
        appendLine("        functions = ${list(model.functions.map { g ->
            "ScriptFunctionSpec(id = ${g.id}, name = ${lit(g.name)}, aliases = ${list(g.aliases.map(::lit))}, onModule = ${g.placement.onModule}, onGlobal = ${g.placement.onGlobal}, attributes = ${g.attributes}, length = ${g.length})"
        }, "        ")},")
        appendLine("        accessors = ${list(model.accessors.map { a ->
            "ScriptAccessorSpec(id = ${a.id}, name = ${lit(a.name)}, getter = ${a.isGetter}, writable = ${a.mutable}, onModule = ${a.placement.onModule}, onGlobal = ${a.placement.onGlobal}, attributes = ${a.attributes})"
        }, "        ")},")
        appendLine("        javaClasses = ${list(model.javaClasses.map { j ->
            "ScriptJavaClassSpec(name = ${lit(j.name)}, type = ${j.type}::class.java, onModule = ${j.placement.onModule}, onGlobal = ${j.placement.onGlobal}, attributes = ${j.attributes})"
        }, "        ")},")
        appendLine("    )")
    }

    private fun StringBuilder.appendCreate(model: ModuleModel) {
        val m = model.qualifiedName
        val body = when (model.instance) {
            ModuleInstance.OBJECT -> m
            ModuleInstance.NO_ARG -> "$m()"
            ModuleInstance.RUNTIME -> "$m(runtime ?: throw IllegalStateException(${lit("Script module ${model.name} needs a ScriptRuntime")}))"
        }
        appendLine("    override fun create(runtime: ScriptRuntime?): $m = $body")
    }

    private fun StringBuilder.appendCall(model: ModuleModel) {
        appendLine("    override fun call(module: ${model.qualifiedName}, id: Int, cx: Context, scope: VarScope, thisObj: Any?, args: Array<out Any?>): Any? = when (id) {")
        model.functions.forEach { appendLine("        ${it.id} -> f${it.id}(module, cx, scope, args)") }
        if (model.invoke != null) appendLine("        ScriptModuleBinding.INVOKE -> invoke(module, cx, scope, args)")
        if (model.construct != null) appendLine("        ScriptModuleBinding.CONSTRUCT -> construct(module, cx, scope, args)")
        appendLine("        else -> throw ScriptArgs.unknownMember(${lit(model.name)}, id)")
        appendLine("    }")
    }

    private fun StringBuilder.appendGet(model: ModuleModel) {
        appendLine("    override fun get(module: ${model.qualifiedName}, id: Int, scope: VarScope): Any? = when (id) {")
        model.accessors.forEach { a ->
            appendLine("        ${a.id} -> ScriptArgs.toJs(scope, module.${id(a.kotlinName)}${if (a.isFunction) "()" else ""})")
        }
        appendLine("        else -> throw ScriptArgs.unknownMember(${lit(model.name)}, id)")
        appendLine("    }")
    }

    private fun StringBuilder.appendSet(model: ModuleModel) {
        val writable = model.accessors.filter { it.mutable && it.setterParam != null }
        appendLine("    override fun set(module: ${model.qualifiedName}, id: Int, value: Any?) {")
        appendLine("        when (id) {")
        writable.forEach { a ->
            appendLine("            ${a.id} -> module.${id(a.kotlinName)} = ${convert(a.setterParam!!, "value", "${model.name}.${a.name}")}")
        }
        appendLine("            else -> throw ScriptArgs.unknownMember(${lit(model.name)}, id)")
        appendLine("        }")
        appendLine("    }")
    }

    /**
     * One private dispatcher per script function: trailing `undefined` arguments beyond the required ones count as
     * omitted, the argument count selects the overloads, and argument type guards decide between overloads with the
     * same count.
     */
    private fun StringBuilder.appendDispatcher(functionName: String, display: String, overloads: List<Overload>, model: ModuleModel, constructor: Boolean = false) {
        val m = model.qualifiedName
        val minRequired = overloads.minOf { it.required }
        val finiteMax = overloads.mapNotNull { it.max }.maxOrNull() ?: -1
        val varargs = overloads.filter { it.vararg }
        val limit = maxOf(finiteMax, varargs.maxOfOrNull { it.required } ?: -1)
        val maxLabel = if (varargs.isNotEmpty()) -1 else finiteMax
        overloads.forEach { appendLine("    // ${it.signature} -> ${it.returnType}  (${it.source})") }
        appendLine("    private fun $functionName(module: $m, cx: Context, scope: VarScope, args: Array<out Any?>): Any? {")
        appendLine("        val n = ScriptArgs.count(args, $minRequired)")
        if (overloads.size == 1 && overloads[0].vararg) {
            appendLine("        return if (n >= $minRequired) ${result(overloads[0], null, display, constructor)} else throw ScriptArgs.arityError(${lit(display)}, $minRequired, -1, n)")
            appendLine("    }")
            return
        }
        appendLine("        return when (n) {")
        for (count in 0..limit) {
            val candidates = overloads.filter { count >= it.required && (it.max == null || count <= it.max!!) }
            if (candidates.isEmpty()) continue
            appendLine("            $count -> ${branch(candidates, count.toString(), display, constructor)}")
        }
        val tail = if (varargs.isNotEmpty()) {
            "if (n > $limit) ${branch(varargs, "n", display, constructor)} else throw ScriptArgs.arityError(${lit(display)}, $minRequired, $maxLabel, n)"
        } else {
            "throw ScriptArgs.arityError(${lit(display)}, $minRequired, $maxLabel, n)"
        }
        appendLine("            else -> $tail")
        appendLine("        }")
        appendLine("    }")
    }

    private fun branch(candidates: List<Overload>, count: String, display: String, constructor: Boolean): String {
        val fixed = count.toIntOrNull()
        if (candidates.size == 1) return result(candidates[0], fixed, display, constructor)
        val ordered = candidates.sortedBy { o -> if (guard(o, fixed) == "true") 1 else 0 }
        return buildString {
            append("when {")
            ordered.forEach { o -> append(" ${guard(o, fixed)} -> ${result(o, fixed, display, constructor)};") }
            val scriptName = display.substringAfterLast('.')
            append(" else -> throw ScriptArgs.noOverload(${lit(display)}, args, ${lit(candidates.joinToString(" | ") { it.signature(scriptName) })}) }")
        }
    }

    /** Type tests of the arguments a candidate takes positionally; vararg elements are converted, not tested. */
    private fun guard(overload: Overload, count: Int?): String {
        val params = overload.scriptParams.filterNot { it.vararg }
        val n = count ?: params.size
        val tests = params.take(n).mapIndexedNotNull { index, p ->
            val test = when {
                p.kind.guard == null -> null
                p.kind == ParamKind.TYPED -> "ScriptArgs.isInstance(args[$index], ${p.rawClass}::class.java)"
                else -> "ScriptArgs.${p.kind.guard}(args[$index])"
            } ?: return@mapIndexedNotNull null
            if (p.nullable) "(ScriptArgs.isNullish(args[$index]) || $test)" else test
        }
        return if (tests.isEmpty()) "true" else tests.joinToString(" && ")
    }

    private fun result(overload: Overload, count: Int?, display: String, constructor: Boolean): String {
        val call = "module.${id(overload.kotlinName)}(${arguments(overload, count, display)})"
        return when {
            constructor -> "ScriptArgs.constructed(scope, $call)"
            overload.returnsUnit -> "ScriptArgs.undefined($call)"
            else -> "ScriptArgs.toJs(scope, $call)"
        }
    }

    /**
     * Positional arguments; once an optional parameter is omitted the following ones (a vararg) are passed by name.
     */
    private fun arguments(overload: Overload, count: Int?, display: String): String {
        var index = 0
        var named = false
        return overload.params.mapNotNull { p ->
            val prefix = if (named) "${id(p.name)} = " else ""
            when {
                p.kind.injected != null -> "$prefix${p.kind.injected}"
                p.vararg -> "$prefix*ScriptArgs.${p.kind.varargConverter}(args, ${index++}, ${lit(display)}, ${lit(p.name)})"
                count != null && index >= count -> null.also { index++; named = true }
                else -> "$prefix${convert(p, "args[${index++}]", display)}"
            }
        }.joinToString(", ")
    }

    private fun convert(p: Param, value: String, display: String): String {
        val suffix = if (p.nullable) "OrNull" else ""
        return when (p.kind) {
            ParamKind.RAW -> if (p.nullable) value else "ScriptArgs.nonNullish($value, ${lit(display)}, ${lit(p.name)})"
            ParamKind.TYPED -> "ScriptArgs.typed$suffix($value, ${p.rawClass}::class.java, ${lit(display)}, ${lit(p.name)})"
            ParamKind.LIST, ParamKind.MAP -> "(ScriptArgs.${p.kind.converter}$suffix($value, ${lit(display)}, ${lit(p.name)}) as ${p.type})"
            else -> "ScriptArgs.${p.kind.converter}$suffix($value, ${lit(display)}, ${lit(p.name)})"
        }
    }

    private fun list(items: List<String>, indent: String = ""): String = when {
        items.isEmpty() -> "listOf()"
        indent.isEmpty() -> items.joinToString(", ", "listOf(", ")")
        else -> items.joinToString(",\n$indent    ", "listOf(\n$indent    ", ",\n$indent)")
    }

    /** A Kotlin string literal: quotes, backslashes and dollar signs escaped, non-ASCII as unicode escapes. */
    fun lit(value: String): String = buildString {
        append('"')
        value.forEach { c ->
            when {
                c == '\\' -> append("\\\\")
                c == '"' -> append("\\\"")
                c == '$' -> append("\\$")
                c == '\n' -> append("\\n")
                c.code < 0x20 || c.code > 0x7e -> append("\\u").append("%04x".format(c.code))
                else -> append(c)
            }
        }
        append('"')
    }

    private val KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
        "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
    )

    private fun id(name: String): String = if (name in KEYWORDS || !name.all { it.isLetterOrDigit() || it == '_' }) "`$name`" else name

}
